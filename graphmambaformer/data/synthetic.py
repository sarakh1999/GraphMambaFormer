# Modality-specific decoration
# --------------------------------------------------------------------------- #
def _flip_cigar_op_at_read_pos(
    cigar: list[tuple[str, int]], read_pos: int, new_op: str = "X"
) -> list[tuple[str, int]]:
    """Return a CIGAR with the query-consuming op at ``read_pos`` set to ``new_op``.

    Only affects query-consuming ops (``=``, ``X``, ``I``, ``S``); no-op if the
    position lands on a non-``=`` op (so conversions on insertions are ignored).
    """
    ops: list[str] = []
    for op, n in cigar:
        ops.extend([op] * n)
    q = -1  # index into query-consuming symbols
    for idx, op in enumerate(ops):
        if op in ("=", "X", "I", "S"):
            q += 1
            if q == read_pos:
                if op == "=":
                    ops[idx] = new_op
                break
    return _rle_cigar(ops)


def _op_at_read_pos(cigar: list[tuple[str, int]], read_pos: int) -> Optional[str]:
    """Return the query-consuming CIGAR op covering ``read_pos`` (or ``None``)."""
    q = 0  # first query index of the current op
    for op, n in cigar:
        if op in ("=", "X", "I", "S"):
            if q <= read_pos < q + n:
                return op
            q += n
    return None


def _decorate_modality(rng: random.Random, cfg: SyntheticConfig, rec: ReadRecord) -> None:
    """Add modality-conditional head labels (Figure 1C)."""
    m = rec.modality
    if m == "bisulfite":
        # methylation state at CpG sites; unmethylated C -> T "conversion". A
        # conversion is a real sequence change vs. the reference, so the truth
        # CIGAR op at that position becomes a mismatch ('X').
        chars = list(rec.seq)
        for i in range(len(chars) - 1):
            # only genomic (reference-matched) cytosines are bisulfite substrates
            if chars[i] == "C" and chars[i + 1] == "G" and _op_at_read_pos(rec.cigar, i) == "=":
                methylated = rng.random() < 0.5
                rec.methylation.append((i, int(methylated)))
                if not methylated:
                    chars[i] = "T"  # bisulfite conversion -> now a mismatch
                    rec.cigar = _flip_cigar_op_at_read_pos(rec.cigar, i, "X")
        rec.seq = "".join(chars)
    elif m == "rna_seq":
        # a splice junction = a large gap; label its read-position boundary
        if len(rec.seq) > 20:
            donor = len(rec.seq) // 2
            rec.splice_junctions.append((donor, donor + 1))
    elif m in ("single_cell", "linked_reads"):
        rec.barcode = "".join(rng.choice(BASES) for _ in range(16))
        rec.umi = "".join(rng.choice(BASES) for _ in range(12))
        prefix = rec.barcode + rec.umi
        rec.seq = prefix + rec.seq
        rec.quals = [cfg.qual_match[1]] * len(prefix) + rec.quals
        rec.ref_positions = [-1] * len(prefix) + rec.ref_positions
        rec.cigar = [("S", len(prefix))] + rec.cigar  # soft-clip the barcode/UMI


# --------------------------------------------------------------------------- #
# Edge cases
# --------------------------------------------------------------------------- #
def _make_edge_cases(rng: random.Random, cfg: SyntheticConfig, refs: list[Reference]) -> list[ReadRecord]:
    ref = refs[0]
    cases: list[ReadRecord] = []

    def tag(rec: ReadRecord, name: str) -> ReadRecord:
        rec.edge_case = name
        return rec

    # 1. empty read
    cases.append(
        tag(
            ReadRecord(
                read_id="edge_empty", ref_id=ref.ref_id, modality="ont", seq="",
                quals=[], ref_start=0, ref_end=0, strand=1, cigar=[], ref_positions=[], mapq=0,
            ),
            "empty_read",
        )
    )

    # 2. very short read (< k)
    short = _simulate_read(rng, cfg, ref, "edge_short", "ont", read_len=cfg.kmer - 3, strand=1)
    cases.append(tag(short, "shorter_than_k"))

    # 3. all-N read (UNK tokens throughout)
    ncase = ReadRecord(
        read_id="edge_all_n", ref_id=ref.ref_id, modality="ont", seq="N" * 60,
        quals=[10] * 60, ref_start=0, ref_end=0, strand=1, cigar=[("I", 60)],
        ref_positions=[-1] * 60, mapq=0,
    )
    cases.append(tag(ncase, "all_n_read"))

    # 4. homopolymer-only read: a low-complexity read that does not map
    #    uniquely (unmapped), exercising homopolymer tokenization/encoding.
    base = rng.choice(BASES)
    hp = base * 80
    hp_rec = ReadRecord(
        read_id="edge_homopolymer", ref_id=ref.ref_id, modality="ont", seq=hp,
        quals=[15] * len(hp), ref_start=0, ref_end=0, strand=1,
        cigar=[("I", len(hp))], ref_positions=[-1] * len(hp), mapq=0,
    )
    cases.append(tag(hp_rec, "homopolymer_only"))

    # 5. fully-repeat read (many false seeds, low MAPQ)
    rep = _simulate_read(rng, cfg, ref, "edge_repeat", "ont", force_region_repeat=True, strand=1)
    cases.append(tag(rep, "repeat_region"))

    # 6. reverse-strand read
    revr = _simulate_read(rng, cfg, ref, "edge_reverse", "pacbio_hifi", strand=-1)
    cases.append(tag(revr, "reverse_strand"))

    # 7. chimeric read (two distant reference regions concatenated)
    a = _simulate_read(rng, cfg, ref, "edge_chimeric_a", "ont",
                       ref_start=0, read_len=cfg.read_len_min // 2, strand=1)
    b = _simulate_read(rng, cfg, ref, "edge_chimeric_b", "ont",
                       ref_start=len(ref.seq) - cfg.read_len_min, read_len=cfg.read_len_min // 2, strand=1)
    chim = ReadRecord(
        read_id="edge_chimeric", ref_id=ref.ref_id, modality="ont",
        seq=a.seq + b.seq, quals=a.quals + b.quals,
        ref_start=a.ref_start, ref_end=a.ref_end, strand=1,
        cigar=a.cigar + [("S", len(b.seq))],
        ref_positions=a.ref_positions + [-1] * len(b.seq),
        mapq=min(a.mapq, b.mapq), is_chimeric=True,
        # supplementary aligns the b-part; soft-clip the a-part so its CIGAR
        # spans the full read (reciprocal of the primary's trailing soft-clip).
        supplementary={"ref_start": b.ref_start, "ref_end": b.ref_end,
                       "strand": b.strand, "cigar": [("S", len(a.seq))] + b.cigar},
    )
    chim.seeds = _extract_seeds(rng, cfg, ref, chim)
    cases.append(tag(chim, "chimeric"))

    return cases


# --------------------------------------------------------------------------- #
# Top-level generation
# --------------------------------------------------------------------------- #
def generate_dataset(cfg: Optional[SyntheticConfig] = None) -> SyntheticDataset:
    """Generate a fully-labelled synthetic dataset from ``cfg`` (default: tiny)."""
    cfg = cfg or SyntheticConfig()
    cfg.validate()
    rng = random.Random(cfg.seed)
    _REF_INDEX_CACHE.clear()

    references = {
        rid: _generate_reference(rng, cfg, rid) for rid in range(cfg.num_references)
    }
    ref_list = list(references.values())

    def make_reads(n: int, split: str) -> list[ReadRecord]:
        recs: list[ReadRecord] = []
        for i in range(n):
            ref = ref_list[i % len(ref_list)]
            modality = cfg.modalities[i % len(cfg.modalities)]
            rec = _simulate_read(rng, cfg, ref, f"{split}_{i}", modality)
            _decorate_modality(rng, cfg, rec)
            recs.append(rec)
        return recs

    splits: dict[str, list[ReadRecord]] = {
        "train": make_reads(cfg.n_train, "train"),
        "val": make_reads(cfg.n_val, "val"),
        "test": make_reads(cfg.n_test, "test"),
    }

    if cfg.include_all_modalities:
        extra = [m for m in ("rna_seq", "bisulfite", "single_cell", "linked_reads")]
        specials: list[ReadRecord] = []
        for j, m in enumerate(extra):
            ref = ref_list[j % len(ref_list)]
            rec = _simulate_read(rng, cfg, ref, f"modality_{m}", m)
            _decorate_modality(rng, cfg, rec)
            specials.append(rec)
        splits["modality"] = specials

    if cfg.include_edge_cases:
        splits["edge"] = _make_edge_cases(rng, cfg, ref_list)

    return SyntheticDataset(references=references, splits=splits, config=cfg)


# --------------------------------------------------------------------------- #
# Reconstruction / verification helpers (used by scripts/verify_stages.py)
# --------------------------------------------------------------------------- #
def cigar_consumed(cigar: list[tuple[str, int]]) -> tuple[int, int]:
    """Return (query_len, ref_len) consumed by a CIGAR (ops '=','X','I','D','S')."""
    q = r = 0
    for op, n in cigar:
        if op in ("=", "X"):
            q += n
            r += n
        elif op == "I" or op == "S":
            q += n
        elif op == "D":
            r += n
    return q, r


def verify_read_alignment(rec: ReadRecord, ref: Reference) -> list[str]:
    """Return a list of human-readable problems ('' means fully consistent)."""
    problems: list[str] = []
    q, r = cigar_consumed(rec.cigar)
    if q != len(rec.seq):
        problems.append(f"CIGAR query len {q} != read len {len(rec.seq)}")
    if not rec.is_chimeric and rec.edge_case not in ("all_n_read",):
        expected_ref = rec.ref_end - rec.ref_start
        if r != expected_ref and rec.edge_case is None:
            problems.append(f"CIGAR ref len {r} != span {expected_ref}")
    if len(rec.ref_positions) != len(rec.seq):
        problems.append("ref_positions length != read length")
    return problems
